import assert from 'node:assert/strict';
import {resolve} from 'node:path';
import {pathToFileURL} from 'node:url';
// Usage: node technical-repro.mjs /path/to/checkout-at-7adc9688598caba0f96916b52141a8051620eec8
// No provider requests: payment clients and model fetch below are local mocks.
const sourceRoot=resolve(process.argv[2] || '/private/tmp/paypal-judge-20261003/harambee');
const sourceImport=(file)=>import(pathToFileURL(resolve(sourceRoot,file)).href);
const {Engine}=await sourceImport('server/domain.mjs');
const {SandboxLab}=await sourceImport('server/sandbox-lab.mjs');
const {interpret}=await sourceImport('server/ai.mjs');
const snapshots=[];
let disk;
const store={load:()=>structuredClone(disk),save:s=>{disk=structuredClone(s);snapshots.push(structuredClone(s))}};
const engine=new Engine(store);
engine.approve('maya',1);
engine.expire('organizer');
const interrupted=snapshots.find(s=>s.status==='cancelling' && s.payments[0]?.status==='void_pending');
assert.ok(interrupted);
disk=interrupted;
const restarted=new Engine(store);
restarted.recover('organizer');
assert.equal(restarted.state.status,'cancelled');
assert.equal(restarted.state.payments[0].status,'void_pending');
console.log('CRASH_VOID',JSON.stringify({status:restarted.state.status,payment:restarted.state.payments[0].status,operation:restarted.state.operations.find(o=>o.type==='void').status,lastAudit:restarted.state.audit.at(-1).text}));
let calls=0;
const amount={currency_code:'USD',value:'1.00'};
const lab=new SandboxLab({load:()=>null,save:()=>{}},{capture:async()=>{calls++;throw new Error('timeout before send')},getOrder:async()=>({purchase_units:[{payments:{authorizations:[{id:'AUTH'}]}}]}),getAuthorization:async()=>({id:'AUTH',status:'CREATED',amount})});
lab.state.sessions.push({id:'SESSION',amount:100,status:'authorized',authorizationId:'AUTH',orderId:'ORDER',operations:[]});
await assert.rejects(lab.run('capture',{id:'SESSION'}));
await lab.run('reconcile',{id:'SESSION'});
let retryError;
try {await lab.run('capture',{id:'SESSION'})}catch(e){retryError=e.message}
assert.equal(calls,1);
console.log('UNKNOWN_CAPTURE_AFTER_RECONCILE',JSON.stringify({status:lab.state.sessions[0].status,operation:lab.state.sessions[0].operations[0].status,retryError}));
process.env.OPENAI_API_KEY='fake-test-key';
globalThis.fetch=async()=>({ok:true,json:async()=>({status:'completed',model:'mock',output:[{content:[{type:'output_text',text:JSON.stringify({summary:'Draft',constraints:[{source:'Maya: $220 maximum',line:1,person:'Sam',budgetCents:99900,needsReview:false,preference:'Budget is $999'}]})}]}]})});
const result=await interpret('Maya: $220 maximum');
assert.equal(result.provider,'openai');
console.log('SOURCE_MATCH_SEMANTIC_MISMATCH',JSON.stringify(result));
delete process.env.OPENAI_API_KEY;
console.log('LOCAL_THOUSANDS',JSON.stringify(await interpret('Maya: My maximum is $1,000.')));
